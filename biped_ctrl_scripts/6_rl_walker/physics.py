"""Reusable hybrid simulator backed by the bootcamp's generated dynamics.

This module is intentionally an adapter, not a second physics model.  It calls
the mass matrix, bias vector, contact Jacobians, Jacobian derivatives,
collision guard and impact maps generated under ``5_walker_3D_control``.
"""

from __future__ import annotations

from dataclasses import dataclass
import importlib
from pathlib import Path
import sys
from typing import Callable

import numpy as np


HERE = Path(__file__).resolve().parent
WALKER_ROOT = HERE.parent / "5_walker_3D_control" / "f_walker_3D"
KERNEL_ROOT = WALKER_ROOT / "dynamics" / "compiled_funcs"
FUNCS_ROOT = WALKER_ROOT / "dynamics" / "funcs"


def _import_from(folder: Path, module: str):
    folder_string = str(folder)
    if folder_string not in sys.path:
        sys.path.insert(0, folder_string)
    return importlib.import_module(module)


def _load_kernels() -> dict[str, Callable]:
    specs = {
        "bias": ("B_matrix", "wrapper_module_0"),
        "collision": ("collision", "wrapper_module_1"),
        "jac_l": ("J_l_ss", "wrapper_module_2"),
        "jac_r": ("J_r_ss", "wrapper_module_3"),
        "jacdot_l": ("Jdot_l_ss", "wrapper_module_4"),
        "jacdot_r": ("Jdot_r_ss", "wrapper_module_5"),
        "mass": ("Mass_matrix", "wrapper_module_6"),
        "push_l": ("P_L", "wrapper_module_7"),
        "push_r": ("P_R", "wrapper_module_8"),
    }
    loaded: dict[str, Callable] = {}
    try:
        for name, (folder, module) in specs.items():
            loaded[name] = _import_from(KERNEL_ROOT / folder, module).autofunc_c
    except ImportError as error:
        raise ImportError(
            "The custom walker kernels are not built. Run "
            "`python3 biped_ctrl_scripts/6_rl_walker/build_physics.py`."
        ) from error
    return loaded


@dataclass(frozen=True)
class WalkerParameters:
    hip_half_width: float = 0.1
    torso_length: float = 1.0
    thigh_length: float = 0.5
    calf_length: float = 0.5
    gravity: float = 9.8
    torso_mass: float = 70.0
    thigh_mass: float = 10.0
    calf_mass: float = 5.0
    torso_ix: float = 5.0
    torso_iy: float = 3.0
    torso_iz: float = 2.0
    thigh_ix: float = 1.0
    thigh_iy: float = 0.3
    thigh_iz: float = 2.0
    calf_ix: float = 0.5
    calf_iy: float = 0.15
    calf_iz: float = 1.0
    # Same pre-impact push used by walker_3D_control.py. Set to zero to study a
    # passive collision without the original powered-walker impulse.
    push_fraction: float = 0.60

    @property
    def kine(self) -> tuple[float, float, float, float]:
        return (
            self.hip_half_width,
            self.torso_length,
            self.thigh_length,
            self.calf_length,
        )

    @property
    def push_impulse(self) -> float:
        mass = self.torso_mass + 2.0 * self.thigh_mass + 2.0 * self.calf_mass
        leg_length = self.thigh_length + self.calf_length
        return self.push_fraction * mass * np.sqrt(self.gravity * leg_length)


class Walker3DPhysics:
    """The repository's 14-DoF constrained single-stance/impact model."""

    nq = 14
    nu = 8
    actuated = slice(6, 14)

    def __init__(self, params: WalkerParameters | None = None):
        self.params = params or WalkerParameters()
        self.kernels = _load_kernels()
        self._kinematics = {}
        for name in (
            "p_H",
            "p_LH",
            "p_RH",
            "p_LK",
            "p_RK",
            "p_LA",
            "p_RA",
            "p_Hip_L_init",
            "p_Hip_R_init",
            "v_Hip_L_init",
            "v_Hip_R_init",
        ):
            module = _import_from(FUNCS_ROOT, f"get_{name}")
            # The autogenerated numeric files import SymPy's scalar trig
            # functions. Rebinding only sin/cos to NumPy preserves the exact
            # expressions while avoiding symbolic-object construction in every
            # simulation step.
            module.sin = np.sin
            module.cos = np.cos
            self._kinematics[name] = module.__dict__[f"get_{name}"]

    def standing_state(self, stance_leg: str = "r") -> np.ndarray:
        """Return exactly straight legs/torso, zero velocity, stance foot at 0."""
        state = np.zeros(2 * self.nq, dtype=np.float64)
        self.project_stance(state, stance_leg, np.zeros(3))
        return state

    def _mass_args(self, q: np.ndarray) -> list[float]:
        p = self.params
        return [
            *q[3:14],
            *p.kine,
            p.torso_mass,
            p.thigh_mass,
            p.calf_mass,
            p.torso_ix,
            p.torso_iy,
            p.torso_iz,
            p.thigh_ix,
            p.thigh_iy,
            p.thigh_iz,
            p.calf_ix,
            p.calf_iy,
            p.calf_iz,
        ]

    def _bias_args(self, q: np.ndarray, qdot: np.ndarray) -> list[float]:
        p = self.params
        return [
            *q[3:14],
            *qdot,
            *np.zeros(14),
            *p.kine,
            p.gravity,
            p.torso_mass,
            p.thigh_mass,
            p.calf_mass,
            p.torso_ix,
            p.torso_iy,
            p.torso_iz,
            p.thigh_ix,
            p.thigh_iy,
            p.thigh_iz,
            p.calf_ix,
            p.calf_iy,
            p.calf_iz,
        ]

    def _jacobian(self, q: np.ndarray, leg: str) -> np.ndarray:
        p = self.params
        if leg == "l":
            args = [*q[3:10], p.hip_half_width, p.thigh_length, p.calf_length]
            return np.asarray(self.kernels["jac_l"](*args), dtype=np.float64)
        if leg == "r":
            args = [*q[3:6], *q[10:14], p.hip_half_width, p.thigh_length, p.calf_length]
            return np.asarray(self.kernels["jac_r"](*args), dtype=np.float64)
        raise ValueError("stance leg must be 'l' or 'r'")

    def _jacobian_dot(self, q: np.ndarray, qdot: np.ndarray, leg: str) -> np.ndarray:
        p = self.params
        if leg == "l":
            args = [
                *q[3:10],
                *qdot[3:10],
                p.hip_half_width,
                p.thigh_length,
                p.calf_length,
            ]
            return np.asarray(self.kernels["jacdot_l"](*args), dtype=np.float64)
        if leg == "r":
            args = [
                *q[3:6],
                *q[10:14],
                *qdot[3:6],
                *qdot[10:14],
                p.hip_half_width,
                p.thigh_length,
                p.calf_length,
            ]
            return np.asarray(self.kernels["jacdot_r"](*args), dtype=np.float64)
        raise ValueError("stance leg must be 'l' or 'r'")

    def acceleration(self, state: np.ndarray, torque: np.ndarray, stance_leg: str) -> np.ndarray:
        """Solve the original 17x17 KKT single-stance equations."""
        q, qdot = state[:14], state[14:]
        mass = np.asarray(self.kernels["mass"](*self._mass_args(q)), dtype=np.float64)
        bias = np.asarray(self.kernels["bias"](*self._bias_args(q, qdot)), dtype=np.float64).reshape(14)
        jac = self._jacobian(q, stance_leg)
        jacdot = self._jacobian_dot(q, qdot, stance_leg)

        system = np.zeros((17, 17), dtype=np.float64)
        rhs = np.zeros(17, dtype=np.float64)
        system[:14, :14] = mass
        system[:14, 14:] = -jac.T
        system[14:, :14] = jac
        rhs[:14] = bias
        rhs[6:14] += np.asarray(torque, dtype=np.float64).reshape(8)
        rhs[14:] = -(jacdot @ qdot)
        return np.linalg.solve(system, rhs)[:14]

    def derivative(self, state: np.ndarray, torque: np.ndarray, stance_leg: str) -> np.ndarray:
        return np.concatenate((state[14:], self.acceleration(state, torque, stance_leg)))

    def integrate(
        self,
        state: np.ndarray,
        torque: np.ndarray,
        stance_leg: str,
        dt: float,
        method: str = "rk4",
    ) -> np.ndarray:
        """Advance continuous dynamics with a fixed torque."""
        if method == "euler":
            qddot = self.acceleration(state, torque, stance_leg)
            result = state.copy()
            result[14:] += dt * qddot
            result[:14] += dt * result[14:]
            return result
        if method != "rk4":
            raise ValueError("method must be 'euler' or 'rk4'")
        f = lambda x: self.derivative(x, torque, stance_leg)
        k1 = f(state)
        k2 = f(state + 0.5 * dt * k1)
        k3 = f(state + 0.5 * dt * k2)
        k4 = f(state + dt * k3)
        return state + dt * (k1 + 2.0 * k2 + 2.0 * k3 + k4) / 6.0

    def foot_position(self, state: np.ndarray, leg: str) -> np.ndarray:
        function = self._kinematics["p_LA" if leg == "l" else "p_RA"]
        return np.asarray(function(*state[:14], *self.params.kine), dtype=np.float64)

    def body_points(self, state: np.ndarray) -> dict[str, np.ndarray]:
        """Return joint locations from the original symbolic kinematics."""
        args = (*state[:14], *self.params.kine)
        names = ("p_H", "p_LH", "p_RH", "p_LK", "p_RK", "p_LA", "p_RA")
        points = {
            name[2:]: np.asarray(self._kinematics[name](*args), dtype=np.float64)
            for name in names
        }
        points["B"] = np.asarray(state[:3], dtype=np.float64).copy()
        return points

    def collision_height(self, state: np.ndarray) -> float:
        q = state[:14]
        p = self.params
        args = [*q[3:14], p.hip_half_width, p.thigh_length, p.calf_length]
        return float(self.kernels["collision"](*args))

    def project_stance(self, state: np.ndarray, leg: str, anchor: np.ndarray) -> None:
        """Remove integration drift in the stance position/velocity constraints."""
        q, qdot = state[:14], state[14:]
        side = "L" if leg == "l" else "R"
        base = self._kinematics[f"p_Hip_{side}_init"](
            0.0, 0.0, 0.0, *q[3:], *self.params.kine
        )
        base_velocity = self._kinematics[f"v_Hip_{side}_init"](
            0.0, 0.0, 0.0, *q[3:], 0.0, 0.0, 0.0, *qdot[3:], *self.params.kine
        )
        q[:3] = np.asarray(anchor) + np.asarray(base, dtype=np.float64)
        qdot[:3] = np.asarray(base_velocity, dtype=np.float64)

    def impact(self, state: np.ndarray, old_stance_leg: str) -> np.ndarray:
        """Apply the repository's perfectly inelastic foot-strike impulse map."""
        q, qdot = state[:14], state[14:]
        new_stance = "r" if old_stance_leg == "l" else "l"
        mass = np.asarray(self.kernels["mass"](*self._mass_args(q)), dtype=np.float64)
        jac_old = self._jacobian(q, old_stance_leg)
        jac_new = self._jacobian(q, new_stance)
        p = self.params

        if old_stance_leg == "l":
            args = [*q[3:10], p.thigh_length, p.calf_length, p.push_impulse]
            push = np.asarray(self.kernels["push_l"](*args), dtype=np.float64).reshape(3)
        else:
            args = [*q[3:6], *q[10:14], p.thigh_length, p.calf_length, p.push_impulse]
            push = np.asarray(self.kernels["push_r"](*args), dtype=np.float64).reshape(3)

        system = np.zeros((17, 17), dtype=np.float64)
        rhs = np.zeros(17, dtype=np.float64)
        system[:14, :14] = mass
        system[:14, 14:] = -jac_new.T
        system[14:, :14] = jac_new
        rhs[:14] = mass @ qdot + jac_old.T @ push
        result = state.copy()
        result[14:] = np.linalg.solve(system, rhs)[:14]
        return result
